import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, join, relative } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const CONTRACTS_DIR = join(ROOT, 'contracts');
const OUT_FILE = join(ROOT, 'src', 'generated', 'soroban-bindings.ts');

function publicFunctions(source) {
  const functions = [];
  const implBlocks = source.match(/#\s*\[\s*contractimpl\s*\][\s\S]*?impl\s+\w+\s*\{([\s\S]*?)\n\}/g) || [];
  for (const block of implBlocks) {
    const re = /pub\s+fn\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(([^)]*)\)/g;
    let match;
    while ((match = re.exec(block))) {
      const name = match[1];
      if (name.startsWith('__')) continue;
      const params = match[2]
        .split(',')
        .map((part) => part.trim())
        .filter((part) => part && !part.startsWith('env:'))
        .map((part) => part.split(':')[0].trim())
        .filter(Boolean);
      functions.push({ name, params });
    }
  }
  return functions.sort((a, b) => a.name.localeCompare(b.name));
}

export function buildBindingManifest() {
  const crates = readdirSync(CONTRACTS_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();

  return crates.map((crateName) => {
    const libPath = join(CONTRACTS_DIR, crateName, 'src', 'lib.rs');
    const source = readFileSync(libPath, 'utf8');
    return {
      crateName,
      wasmFile: `contracts/${crateName}/target/wasm32-unknown-unknown/release/${crateName}.wasm`,
      source: relative(ROOT, libPath).replaceAll('\\', '/'),
      functions: publicFunctions(source),
    };
  });
}

export function renderBindings(manifest) {
  const json = JSON.stringify(manifest, null, 2);
  return `/* eslint-disable */\n// Generated by scripts/generate-soroban-bindings.js. Do not edit by hand.\n\nexport type SorobanBindingFunction = {\n  name: string;\n  params: string[];\n};\n\nexport type SorobanContractBinding = {\n  crateName: string;\n  wasmFile: string;\n  source: string;\n  functions: SorobanBindingFunction[];\n};\n\nexport const sorobanBindings = ${json} as const satisfies readonly SorobanContractBinding[];\n\nexport function getSorobanBinding(crateName: string) {\n  return sorobanBindings.find((binding) => binding.crateName === crateName) ?? null;\n}\n`;
}

export function writeBindings(outFile = OUT_FILE) {
  const manifest = buildBindingManifest();
  mkdirSync(join(ROOT, 'src', 'generated'), { recursive: true });
  const content = renderBindings(manifest);
  writeFileSync(outFile, content);
  return { outFile, manifest };
}

if (process.argv[1] && basename(process.argv[1]) === 'generate-soroban-bindings.js') {
  const { outFile, manifest } = writeBindings();
  console.log(`[bindings] wrote ${outFile} (${manifest.length} contract crates)`);
}
